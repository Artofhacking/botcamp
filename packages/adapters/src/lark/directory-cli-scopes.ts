/** Identity scopes the directory login needs in addition to the command-line catalog. */
export const DIRECTORY_LOGIN_IDENTITY_SCOPES = [
  "contact:user.email:readonly",
  "contact:user.employee:readonly",
] as const;

/** The scopes a directory sign-in or link requests. Extra names are added, never a replacement. */
export function directoryLoginScopes(extra: readonly string[] = []): string[] {
  const scopes: string[] = [];
  const seen = new Set<string>();
  for (const scope of [
    ...DIRECTORY_CLI_USER_SCOPES,
    ...DIRECTORY_LOGIN_IDENTITY_SCOPES,
    ...extra,
  ]) {
    const name = scope.trim();
    if (!name || seen.has(name)) continue;
    seen.add(name);
    scopes.push(name);
  }
  return scopes;
}
